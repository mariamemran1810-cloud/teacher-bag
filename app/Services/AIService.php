<?php

namespace App\Services;

use Illuminate\Support\Facades\Http;

class AIService
{
    public function generateLessonPrep(string $title, string $subject = 'عام'): string
    {
        $key = env('OPENAI_API_KEY');

        if ($key) {
            $response = Http::withToken($key)->timeout(60)->post('https://api.openai.com/v1/chat/completions', [
                'model' => 'gpt-4o-mini',
                'messages' => [
                    ['role' => 'system', 'content' => 'أنت معلم خبير، اكتب كراسة تحضير منسقة بالعربية.'],
                    ['role' => 'user', 'content' => "اكتب كراسة تحضير متكاملة للمادة: $subject، الموضوع: $title، تشمل: الأهداف، الوسائل، المقدمة، العرض، التطبيق، التقويم، الواجب."],
                ],
            ]);

            if ($response->successful()) {
                return $response->json('choices.0.message.content');
            }
        }

        // الرد الاحتياطي عند عدم توفر مفتاح OpenAI
        return "المادة: $subject\nالموضوع: $title\n\n"
            . "الهدف المعرفي: يتعرف الطالب على مفاهيم $title\n"
            . "الهدف المهاري: يطبق الطالب مفاهيم $title عملياً\n"
            . "الهدف الوجداني: يقدّر الطالب أهمية $title في حياته\n"
            . "الوسائل التعليمية: السبورة، بطاقات تعليمية، عروض\n"
            . "التمهيد: سؤال تحفيزي حول $title\n"
            . "خطوات سير الدرس: مقدمة، عرض، تطبيق، تقويم، خاتمة\n"
            . "استراتيجيات التدريس: التعلم التعاوني، حل المشكلات، الاكتشاف\n"
            . "الأنشطة والتطبيقات: أنشطة صفية وجماعية\n"
            . "التقويم: أسئلة شفهية وبطاقات عمل\n"
            . "التلاميذ المتوقع دعمهم: من يعانون من صعوبات تعلم\n"
            . "صعوبات التعلم والمشكلات الملحوظة: التأخر في الاستيعاب، التركيز\n"
            . "الإجراءات العلاجية والإثرائية: أسئلة داعمة، تشجيع، مكافآت\n"
            . "متابعة تطور كل تلميذ سجل مستمر\n"
            . "سجل الدرجات والتقويم المستمر\n"
            . "صفحة الملاحظات: تُدون يومياً\n\n"
            . "المصدر: تم التوليد بواسطة الذكاء الاصطناعي داخل حقيبة المعلمة الرقمية";
    }
}
